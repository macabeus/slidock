/// PowerPoint `presetSubtype` for an ODF sub-type (the inverse of LibreOffice's `getConvertedSubType`).
pub fn pptx_subtype(id: u32, sub: &str) -> Option<u32> {
    if sub.is_empty() {
        return Some(0);
    }
    if let Ok(number) = sub.parse::<u32>() {
        return Some(number);
    }
    let special = match (id, sub) {
        (5, "downward") => Some(5),
        (5, "across") => Some(10),
        (17, "across") => Some(10),
        (18, "right-to-top") => Some(3),
        (18, "right-to-bottom") => Some(6),
        (18, "left-to-top") => Some(9),
        (18, "left-to-bottom") => Some(12),
        _ => None,
    };
    if special.is_some() {
        return special;
    }
    let bare = sub
        .strip_prefix("from-")
        .or_else(|| sub.strip_prefix("to-"))
        .unwrap_or(sub);
    Some(match bare {
        "top" => 1,
        "right" => 2,
        "top-right" => 3,
        "bottom" => 4,
        "horizontal" => 5,
        "bottom-right" => 6,
        "left" => 8,
        "top-left" => 9,
        "vertical" => 10,
        "bottom-left" => 12,
        "in" => 16,
        "vertical-in" => 21,
        "horizontal-in" => 26,
        "out" => 32,
        "out-from-screen-center" => 36,
        "vertical-out" => 37,
        "horizontal-out" => 42,
        "in-slightly" => 272,
        "out-slightly" => 288,
        "in-from-screen-center" => 528,
        _ => return None,
    })
}

