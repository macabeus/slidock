//! `cargo xtask diagnostics [--check]`: writes `docs/diagnostics.md`, the reference of every registered diagnostic
//! code (`DiagnosticCode::ALL`), from the registry in `crates/slidock-ir/src/diagnostics/registry.rs`. `--check`
//! compares instead of writing.

use std::fmt::Write as _;
use std::path::Path;

use slidock_ir::diagnostics::{CodePrefix, DiagnosticCode, Severity};

const USAGE: &str = "usage: cargo xtask diagnostics [--check]";
const FILE: &str = "docs/diagnostics.md";

pub fn run(args: &[String]) -> Result<(), String> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(FILE);
    let text = generate();
    match args.first().map(String::as_str) {
        None => {
            std::fs::write(&path, &text).map_err(|e| format!("{}: {e}", path.display()))?;
            println!("wrote {FILE} ({} codes)", DiagnosticCode::ALL.len());
            Ok(())
        }
        Some("--check") if args.len() == 1 => {
            if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
                println!("{FILE} is up to date");
                Ok(())
            } else {
                Err(format!("{FILE} is stale: run cargo xtask diagnostics"))
            }
        }
        _ => Err(USAGE.to_owned()),
    }
}

/// What a severity means to the reader of a deck, and when the CLI lists it.
fn severity_row(severity: Severity) -> (&'static str, &'static str) {
    match severity {
        Severity::Error => (
            "The input could not be read, or a slide, layout or master (or the whole presentation) could not be \
             converted and is left out. The CLI exits 1, or 2 for a refused input.",
            "always",
        ),
        Severity::Decline => (
            "An element is not shown at all: slidock does not support it.",
            "by default",
        ),
        Severity::Lossy => (
            "Something is shown, but differently from the original: approximated, simplified or partly left out.",
            "by default",
        ),
        Severity::Warning => (
            "The input is malformed or inconsistent; slidock worked around it.",
            "by default",
        ),
        Severity::Info => (
            "A note on how something was converted, which the deck shows faithfully or close to it.",
            "with `-v`",
        ),
    }
}

/// The emitter a code prefix names; `None` for the reserved ones.
fn emitter(prefix: CodePrefix) -> Option<&'static str> {
    match prefix {
        CodePrefix::Ir => Some("the core (input checks, limits, verification)"),
        CodePrefix::Kn => Some("the Keynote reader"),
        CodePrefix::Px => Some("the PowerPoint (PPTX) reader"),
        CodePrefix::Od => Some("the OpenDocument (ODP) reader"),
        CodePrefix::Mid => Some(
            "the passes between reading and writing (placeholders, themes, fonts, text fitting, media)",
        ),
        CodePrefix::Html => Some("the HTML writer"),
        CodePrefix::Gs | CodePrefix::Pd | CodePrefix::Rx | CodePrefix::Exp => None,
    }
}

/// `text` safe in a Markdown table cell.
fn cell(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if matches!(c, '|' | '*' | '_' | '<' | '>' | '[' | ']' | '`' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

pub fn generate() -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Diagnostics\n\n\
         <!-- Generated by `cargo xtask diagnostics` from crates/slidock-ir/src/diagnostics/registry.rs: do not edit. \
         -->\n\n\
         Every diagnostic slidock reports has a code (`MID5401`), a kebab-case name (`font-substituted`), a severity \
         and a message. The CLI prints them on stderr, one per line:\n\n\
         ```text\n\
         lossy   MID5401 font-substituted pp-256 pp-256.3: Calibri is not available; Carlito stands in\n\
         ```\n\n\
         After the severity, code and name come the slide (or layout, or master) and the element it concerns, when \
         there is one. `--emit report` lists them in `report.json`.\n\n\
         ## Severities\n\n\
         | Severity | Meaning | Listed by the CLI |\n\
         | --- | --- | --- |"
    );
    for severity in Severity::ALL {
        let (meaning, listed) = severity_row(severity);
        let _ = writeln!(out, "| `{}` | {meaning} | {listed} |", severity.as_str());
    }
    let _ = writeln!(
        out,
        "\n`-q` lists errors only. Whatever is not listed is counted in the summary line that follows the list.\n\n\
         ## Codes\n\n\
         A code's letters name the part of slidock that reports it. In a message, `{{name}}` stands for a value \
         the diagnostic fills in. *Feature* names the presentation feature whose loss the diagnostic \
         reports, as `report.json` names it."
    );
    // The prefixes in registry order.
    let mut prefixes: Vec<CodePrefix> = Vec::new();
    for code in DiagnosticCode::ALL {
        if !prefixes.contains(&code.prefix()) {
            prefixes.push(code.prefix());
        }
    }
    for prefix in prefixes {
        let Some(emitter) = emitter(prefix) else {
            continue;
        };
        let codes: Vec<DiagnosticCode> = DiagnosticCode::ALL
            .iter()
            .copied()
            .filter(|code| code.prefix() == prefix)
            .collect();
        if codes.is_empty() {
            continue;
        }
        let _ = writeln!(
            out,
            "\n### {}: {emitter}\n\n\
             | Code | Name | Severity | Message | Feature |\n\
             | --- | --- | --- | --- | --- |",
            prefix.as_str()
        );
        for code in codes {
            let feature = code
                .feature()
                .map_or(String::new(), |feature| format!("`{}`", feature.as_str()));
            let _ = writeln!(
                out,
                "| {} | `{}` | {} | {} | {feature} |",
                code.code(),
                code.name(),
                code.severity().as_str(),
                cell(code.template())
            );
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_every_registered_code_once() {
        let text = generate();
        for code in DiagnosticCode::ALL {
            let row = format!("| {} | `{}` |", code.code(), code.name());
            assert_eq!(text.matches(&row).count(), 1, "{row}");
        }
    }

    #[test]
    fn escapes_what_markdown_would_read_in_a_cell() {
        assert_eq!(cell("a | b *c* <d>"), "a \\| b \\*c\\* \\<d\\>");
    }
}
