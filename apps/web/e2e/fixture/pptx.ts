// The smoke deck: a small PPTX written from code, so part of the suite runs without the private corpus. It holds
// our own content only: four slides (one hidden), text in the bundled Liberation faces, a PNG drawn here, speaker
// notes and a fade transition. The package is a stored zip with every part PowerPoint needs and nothing else.
import {
  CLR_MAP,
  EMU,
  NS,
  XML,
  escape,
  gradientPng,
  rels,
  storedZip,
  themeElements,
  tree,
  xfrm,
} from '@slidock/wasm/test/ooxml';

export interface SmokeSlide {
  title: string;
  hidden: boolean;
  notes: string[];
  image: boolean;
}

/** The slides of the smoke deck, in show order. */
export const SMOKE_SLIDES: readonly SmokeSlide[] = [
  {
    title: 'slidock smoke deck',
    hidden: false,
    notes: ['Welcome everyone.', 'This deck is generated by the e2e setup.'],
    image: false,
  },
  { title: 'A picture', hidden: false, notes: ['The picture is a PNG drawn in code.'], image: true },
  { title: 'A hidden slide', hidden: true, notes: [], image: false },
  { title: 'The end', hidden: false, notes: [], image: false },
];

function textBox(id: number, box: [number, number, number, number], size: number, color: string, text: string) {
  return (
    `<p:sp><p:nvSpPr><p:cNvPr id="${id}" name="Text ${id}"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>` +
    `<p:spPr>${xfrm(...box)}<a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/></p:spPr>` +
    '<p:txBody><a:bodyPr wrap="square"/><a:lstStyle/>' +
    `<a:p><a:r><a:rPr lang="en-US" sz="${size * 100}"><a:solidFill><a:srgbClr val="${color}"/></a:solidFill></a:rPr>` +
    `<a:t>${escape(text)}</a:t></a:r></a:p></p:txBody></p:sp>`
  );
}

function band(id: number, box: [number, number, number, number], color: string) {
  return (
    `<p:sp><p:nvSpPr><p:cNvPr id="${id}" name="Band ${id}"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>` +
    `<p:spPr>${xfrm(...box)}<a:prstGeom prst="rect"><a:avLst/></a:prstGeom>` +
    `<a:solidFill><a:srgbClr val="${color}"/></a:solidFill></p:spPr></p:sp>`
  );
}

function picture(id: number, box: [number, number, number, number]) {
  return (
    `<p:pic><p:nvPicPr><p:cNvPr id="${id}" name="Picture ${id}" descr="A gradient"/><p:cNvPicPr/><p:nvPr/></p:nvPicPr>` +
    '<p:blipFill><a:blip r:embed="rIdImage"/><a:stretch><a:fillRect/></a:stretch></p:blipFill>' +
    `<p:spPr>${xfrm(...box)}<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr></p:pic>`
  );
}

const THEME = themeElements('Liberation Sans');

function slideXml(slide: SmokeSlide, index: number): string {
  const content =
    band(2, [0, 0, 720, 12], index % 2 === 0 ? 'EC4899' : 'F97316') +
    textBox(3, [48, 40, 624, 70], 40, '1E1E28', slide.title) +
    textBox(4, [48, 120, 400, 40], 20, '2B2D42', `Slide ${index + 1} of ${SMOKE_SLIDES.length}`) +
    (slide.image ? picture(5, [420, 150, 240, 180]) : '');
  const show = slide.hidden ? ' show="0"' : '';
  const transition = slide.image ? '<p:transition spd="med"><p:fade/></p:transition>' : '';
  return (
    `${XML}<p:sld ${NS}${show}><p:cSld><p:bg><p:bgPr><a:solidFill><a:srgbClr val="EDF2F4"/></a:solidFill>` +
    `<a:effectLst/></p:bgPr></p:bg>${tree(content)}</p:cSld><p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>` +
    `${transition}</p:sld>`
  );
}

function notesXml(notes: readonly string[]): string {
  const paragraphs = notes.map((text) => `<a:p><a:r><a:rPr lang="en-US"/><a:t>${escape(text)}</a:t></a:r></a:p>`);
  const body =
    '<p:sp><p:nvSpPr><p:cNvPr id="2" name="Notes"/><p:cNvSpPr/><p:nvPr><p:ph type="body" idx="1"/></p:nvPr></p:nvSpPr>' +
    `<p:spPr/><p:txBody><a:bodyPr/><a:lstStyle/>${paragraphs.join('')}</p:txBody></p:sp>`;
  return `${XML}<p:notes ${NS}><p:cSld>${tree(body)}</p:cSld></p:notes>`;
}

/** The smoke deck's bytes. */
export function smokePptx(): Uint8Array {
  const text = (value: string) => new TextEncoder().encode(value);
  const files: [string, Uint8Array][] = [];
  const types =
    `${XML}<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
    '<Default Extension="xml" ContentType="application/xml"/>' +
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' +
    '<Default Extension="png" ContentType="image/png"/>' +
    '<Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>' +
    '</Types>';
  files.push(['[Content_Types].xml', text(types)]);
  files.push(['_rels/.rels', text(rels([['rId1', 'officeDocument', 'ppt/presentation.xml']]))]);
  const slideIds = SMOKE_SLIDES.map((_, i) => `<p:sldId id="${256 + i}" r:id="rIdS${i + 1}"/>`).join('');
  files.push([
    'ppt/presentation.xml',
    text(
      `${XML}<p:presentation ${NS}><p:sldMasterIdLst><p:sldMasterId id="2147483648" r:id="rIdM1"/></p:sldMasterIdLst>` +
        `<p:sldIdLst>${slideIds}</p:sldIdLst><p:sldSz cx="${720 * EMU}" cy="${405 * EMU}"/>` +
        `<p:notesSz cx="${405 * EMU}" cy="${720 * EMU}"/></p:presentation>`,
    ),
  ]);
  files.push([
    'ppt/_rels/presentation.xml.rels',
    text(
      rels([
        ['rIdM1', 'slideMaster', 'slideMasters/slideMaster1.xml'],
        ...SMOKE_SLIDES.map((_, i) => [`rIdS${i + 1}`, 'slide', `slides/slide${i + 1}.xml`] as const),
      ]),
    ),
  ]);
  files.push(['ppt/theme/theme1.xml', text(`${XML}<a:theme ${NS} name="Smoke">${THEME}</a:theme>`)]);
  files.push([
    'ppt/slideMasters/slideMaster1.xml',
    text(
      `${XML}<p:sldMaster ${NS}><p:cSld>${tree('')}</p:cSld><p:clrMap ${CLR_MAP}/>` +
        '<p:sldLayoutIdLst><p:sldLayoutId id="2147483649" r:id="rIdL1"/></p:sldLayoutIdLst></p:sldMaster>',
    ),
  ]);
  files.push([
    'ppt/slideMasters/_rels/slideMaster1.xml.rels',
    text(
      rels([
        ['rIdTheme', 'theme', '../theme/theme1.xml'],
        ['rIdL1', 'slideLayout', '../slideLayouts/slideLayout1.xml'],
      ]),
    ),
  ]);
  files.push([
    'ppt/slideLayouts/slideLayout1.xml',
    text(
      `${XML}<p:sldLayout ${NS} type="blank"><p:cSld name="Blank">${tree('')}</p:cSld>` +
        '<p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr></p:sldLayout>',
    ),
  ]);
  files.push([
    'ppt/slideLayouts/_rels/slideLayout1.xml.rels',
    text(rels([['rIdM', 'slideMaster', '../slideMasters/slideMaster1.xml']])),
  ]);
  SMOKE_SLIDES.forEach((slide, i) => {
    const n = i + 1;
    files.push([`ppt/slides/slide${n}.xml`, text(slideXml(slide, i))]);
    const slideRels: [string, string, string][] = [['rIdLayout', 'slideLayout', '../slideLayouts/slideLayout1.xml']];
    if (slide.image) {
      slideRels.push(['rIdImage', 'image', '../media/image1.png']);
    }
    if (slide.notes.length > 0) {
      slideRels.push(['rIdNotes', 'notesSlide', `../notesSlides/notesSlide${n}.xml`]);
      files.push([`ppt/notesSlides/notesSlide${n}.xml`, text(notesXml(slide.notes))]);
    }
    files.push([`ppt/slides/_rels/slide${n}.xml.rels`, text(rels(slideRels))]);
  });
  files.push(['ppt/media/image1.png', gradientPng(96, 72)]);
  return storedZip(files);
}
